// npm run review-list -- <world-id> [<world-id> …]
// Writes docs/review/<world-id>.md: the native-speaker check for a world's new content (every
// new word with its split and stress, every sentence with its picture, Соня's new lines, new
// cards), as tick-box tables to send back with fixes. Run it after adding or changing a world.
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { validateContent } from '../src/reading/engine/validate.ts';
import { taskLogics } from '../src/reading/tasks/logicRegistry.ts';
import { readContent } from './content-files.ts';

interface WordRow {
  id: string;
  split: string;
  emoji: string;
  stress?: number;
}
interface SentenceRow {
  id: string;
  text: string;
  scene?: string;
}
interface RawWorld {
  id: string;
  units?: { letters?: string }[];
}
interface RawLexicon {
  syllables?: string;
  words?: WordRow[];
  sentences?: SentenceRow[];
}

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const wanted = process.argv.slice(2);
const { raw, worldIds, loadErrors } = readContent(root);
const { issues, content } = loadErrors.length ? { issues: loadErrors, content: null } : validateContent(raw, taskLogics);
const errors = issues.filter((i) => i.severity === 'error');
if (!content || errors.length) {
  for (const e of errors) console.error(`✖ ${e.file}: ${e.message}`);
  console.error('Fix the content first (npm run validate-content).');
  process.exit(1);
}
const unknown = wanted.filter((id) => !worldIds.includes(id));
if (!wanted.length || unknown.length) {
  console.error(`Usage: npm run review-list -- <world-id> …  (worlds: ${worldIds.join(', ')})`);
  process.exit(1);
}

const vowels = new Set(content.config.letters.vowels);
/** СО-ВА with stress 1 → СО-ВА́ (the accent goes after the stressed syllable's vowel). */
const stressed = ({ split, stress }: WordRow) => {
  const syllables = split.split('-');
  if (syllables.length < 2 || stress === undefined) return split;
  const s = syllables[stress]!;
  const at = [...s].findIndex((ch) => vowels.has(ch));
  syllables[stress] = [...s].map((ch, i) => (i === at ? `${ch}́` : ch)).join('');
  return syllables.join('-');
};
const lineText = (id: string) => {
  const value = content.voice.get(id);
  return value === undefined ? `(missing line ${id})` : Array.isArray(value) ? value.join(' / ') : value;
};
const table = (head: string[], rows: string[][]) =>
  [`| ✓ | ${head.join(' | ')} |`, `| --- | ${head.map(() => '---').join(' | ')} |`, ...rows.map((r) => `| ☐ | ${r.join(' | ')} |`)].join('\n');

// Lines and cards a world's levels use; "new" means no earlier world used them.
const worlds = content.worlds;
const linesOf = (index: number) =>
  new Set(worlds[index]!.levels.flatMap((l) => [l.intro.voice, `magicDoor.${l.boss.inner}`, ...(l.boss.openedLine ? [l.boss.openedLine] : [])]));
const cardsOf = (index: number) => worlds[index]!.levels.flatMap((l) => (l.reward.card ? [l.reward.card] : []));

for (const worldId of wanted) {
  const index = worlds.findIndex((w) => w.world.id === worldId);
  const { world, levels } = worlds[index]!;
  const source = raw.worlds.find((w) => (w.world.data as RawWorld).id === worldId)!;
  const lexicon = source.lexicon.data as RawLexicon;
  const letters = ((source.world.data as RawWorld).units ?? []).flatMap((u) => (u.letters ? [u.letters] : []));
  const earlierLines = new Set(worlds.slice(0, index).flatMap((_, i) => [...linesOf(i)]));
  const lines = [...linesOf(index)].filter((id) => !earlierLines.has(id)).sort();
  const cards = cardsOf(index).map((id) => content.cards.get(id)!);

  const parts = [
    `# Review: World ${world.order} · ${world.title}`,
    `${levels.length} levels${letters.length ? `; new letters: ${letters.join(', ')}` : ''}. Generated by \`npm run review-list -- ${worldId}\`.`,
    'Please check every row; anything that sounds unnatural, has a wrong split or a wrong stress, write the fix next to it and send it back.',
    [
      '- **Split**: how a Ukrainian primer would divide the word into syllables (one vowel each).',
      '- **Stress**: the stressed vowel carries ́ (e.g. СО-ВА́). One-syllable words have none.',
      '- **Sentences**: should sound like something a parent would say; case forms, agreement and у/в correct.',
    ].join('\n'),
  ];
  if (lexicon.syllables) parts.push(`Drill syllables: ${lexicon.syllables}`);
  if (lexicon.words?.length) {
    parts.push(`## Words (${lexicon.words.length})`, table(['Word', 'Split · stress', 'Picture'], lexicon.words.map((w) => [w.split.replaceAll('-', ''), stressed(w), w.emoji])));
  }
  if (lexicon.sentences?.length) {
    parts.push(`## Sentences (${lexicon.sentences.length})`, table(['Sentence', 'What the picture shows'], lexicon.sentences.map((s) => [s.text, s.scene ? `\`${s.scene}\`` : ''])));
  }
  if (lines.length) {
    parts.push("## Соня's new lines", table(['Line', 'Id'], lines.map((id) => [lineText(id), `\`${id}\``])), '`{nameVoc}` is filled with his name in the vocative (Мишку).');
  }
  if (cards.length) parts.push('## New cards', table(['Card'], cards.map((c) => [`${c.emoji} ${c.name}`])));

  const out = join(root, 'docs', 'review', `${worldId}.md`);
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, `${parts.join('\n\n')}\n`);
  console.log(`✔ ${out.slice(root.length + 1)}: ${lexicon.words?.length ?? 0} words, ${lexicon.sentences?.length ?? 0} sentences, ${lines.length} new lines, ${cards.length} cards`);
}
